using System.Globalization;
using System.Numerics;

namespace WinForward.E2E.Analysis.Json;

/// <summary>
/// The reference's number formatting, reproduced: <c>%.*f</c> with round-half-to-even on the exact
/// binary value, falling back to <c>%.3g</c> when the fixed form would print a non-zero value as
/// zero, and <c>repr</c> for the float text inside <c>verdict.json</c>.
/// </summary>
/// <remarks>
/// <para>.NET's own formatting differs in both places that matter: its <c>F</c> rounding is not
/// half-to-even on the exact double — <c>0.0625</c> at three digits is the midpoint of the grid, and
/// the two implementations print different digits there — and its <c>G</c> prints an upper-case
/// exponent with as few digits as it can. Every number in <c>tables.md</c> is compared as text, so
/// neither difference is cosmetic (D20.5).</para>
/// <para>The rounding is done on the exact rational value of the double (<c>mantissa * 2^exponent</c>)
/// rather than on a decimal approximation of it, which is what makes a midpoint reachable at all: the
/// halves this rounds are exact binary fractions such as <c>0.0625</c>, not the halves a decimal
/// reader would invent.</para>
/// <para>Public because the test project drives it against a CPython vector table
/// (<c>verification/golden/py-number-vectors.json</c>, regenerated by
/// <c>verification/synthetic/make_cp_vectors.py</c>); D20.6 keeps the analyzer free of an
/// <c>InternalsVisibleTo</c>.</para>
/// </remarks>
public static class VerbatimNumber
{
    /// <summary>How many significant digits the <c>%.3g</c> fallback keeps.</summary>
    private const int FallbackPrecision = 3;

    /// <summary>The characters a rendered number consists of when it reads as zero.</summary>
    private const string ZeroText = "0.-";

    /// <summary>One value as <c>%.*f</c> writes it, with the sign of a negative zero kept.</summary>
    /// <param name="value">The value to write.</param>
    /// <param name="digits">How many digits to keep after the point.</param>
    /// <returns>The reference's text, without a unit.</returns>
    public static string Fixed(double value, int digits)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(digits);

        if (Named(value) is { } named)
        {
            return named;
        }

        var sign = IsNegative(value) ? "-" : string.Empty;
        if (IsZero(value))
        {
            return sign + Plain(BigInteger.Zero, digits);
        }

        var (numerator, denominator) = Fraction(Math.Abs(value));
        var scaled = RoundHalfEven(numerator * BigInteger.Pow(10, digits), denominator);
        return sign + Plain(scaled, digits);
    }

    /// <summary>
    /// One value as <c>%.*g</c> writes it: the shorter of the fixed and the exponential form, with the
    /// trailing zeros of the significand removed and the exponent spelled in lower case with a sign
    /// and at least two digits.
    /// </summary>
    /// <param name="value">The value to write.</param>
    /// <param name="precision">How many significant digits to keep; zero means one.</param>
    /// <returns>The reference's text, without a unit.</returns>
    public static string General(double value, int precision)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(precision);

        if (Named(value) is { } named)
        {
            return named;
        }

        var digits = precision == 0 ? 1 : precision;
        var sign = IsNegative(value) ? "-" : string.Empty;
        if (IsZero(value))
        {
            return sign + "0";
        }

        var (numerator, denominator) = Fraction(Math.Abs(value));
        var exponent = DecimalExponent(numerator, denominator);
        var shift = exponent - digits + 1;
        var significand = shift >= 0
            ? RoundHalfEven(numerator, denominator * BigInteger.Pow(10, shift))
            : RoundHalfEven(numerator * BigInteger.Pow(10, -shift), denominator);
        var text = significand.ToString(CultureInfo.InvariantCulture);
        if (text.Length > digits)
        {
            exponent += text.Length - digits;
            text = text[..digits];
        }

        text = text.TrimEnd('0');
        var body = exponent < -4 || exponent >= digits
            ? Exponential(text, exponent)
            : Significant(text, exponent);
        return sign + body;
    }

    /// <summary>
    /// One number as a table cell: the reference's <c>fmt_num</c>, which is the fixed form except where
    /// that form would print a non-zero value as zero, in which case the general form keeps the value
    /// visible instead of rounding it away.
    /// </summary>
    /// <param name="value">The value to write; a JSON null reading has none.</param>
    /// <param name="digits">How many digits the fixed form keeps after the point.</param>
    /// <param name="unit">The unit to append, with no separator.</param>
    /// <returns>The cell's text.</returns>
    public static string Cell(double? value, int digits = 3, string unit = "")
    {
        ArgumentNullException.ThrowIfNull(unit);

        if (value is null)
        {
            return "n/a";
        }

        var text = Fixed(value.Value, digits);
        if (!IsZero(value.Value) && ReadsAsZero(text))
        {
            text = General(value.Value, FallbackPrecision);
        }

        return text + unit;
    }

    /// <summary>
    /// One value as Python's <c>repr</c> writes it, which is the float text <c>json.dumps</c> emits:
    /// the shortest decimal that reads back as the same double, with an integral value keeping a
    /// <c>.0</c> and an exponent used outside <c>1e-05</c> … <c>1e16</c>.
    /// </summary>
    /// <param name="value">The value to write.</param>
    /// <returns>The text, which is a JSON number literal for every finite value.</returns>
    public static string Json(double value)
    {
        if (double.IsNaN(value))
        {
            return "NaN";
        }

        if (double.IsInfinity(value))
        {
            return IsNegative(value) ? "-Infinity" : "Infinity";
        }

        var sign = IsNegative(value) ? "-" : string.Empty;
        var magnitude = Math.Abs(value);
        if (IsZero(magnitude))
        {
            return sign + "0.0";
        }

        var (digits, decimalPoint) = Shortest(magnitude);
        var exponent = decimalPoint - 1;
        var body = exponent is <= -5 or >= 16
            ? Exponential(digits, exponent)
            : Repr(digits, decimalPoint);
        return sign + body;
    }

    /// <summary>The text <c>printf</c> writes for a value that is not a number at all.</summary>
    private static string? Named(double value)
    {
        if (double.IsNaN(value))
        {
            return "nan";
        }

        if (double.IsPositiveInfinity(value))
        {
            return "inf";
        }

        return double.IsNegativeInfinity(value) ? "-inf" : null;
    }

    /// <summary>Whether the sign bit is set, which is how a negative zero is told from a positive one.</summary>
    private static bool IsNegative(double value) => BitConverter.DoubleToUInt64Bits(value) >> 63 != 0;

    /// <summary>Whether the magnitude is zero, told from the bit pattern so both zeros answer yes.</summary>
    private static bool IsZero(double value) => (BitConverter.DoubleToUInt64Bits(value) << 1) == 0;

    /// <summary>
    /// The value as an exact fraction: a double is a mantissa times a power of two, so every finite
    /// value is one integer over another and neither the rounding nor the digits lose anything.
    /// </summary>
    private static (BigInteger Numerator, BigInteger Denominator) Fraction(double magnitude)
    {
        var bits = BitConverter.DoubleToUInt64Bits(magnitude);
        var exponent = (int)((bits >> 52) & 0x7ff);
        var mantissa = bits & 0x000fffffffffffffUL;
        if (exponent == 0)
        {
            exponent = -1074;
        }
        else
        {
            mantissa |= 1UL << 52;
            exponent -= 1075;
        }

        var numerator = new BigInteger(mantissa);
        return exponent >= 0
            ? (numerator << exponent, BigInteger.One)
            : (numerator, BigInteger.One << -exponent);
    }

    /// <summary>The quotient, rounded to the nearest integer with a tie going to the even one.</summary>
    private static BigInteger RoundHalfEven(BigInteger numerator, BigInteger denominator)
    {
        var quotient = BigInteger.DivRem(numerator, denominator, out var remainder);
        var twice = remainder << 1;
        var comparison = twice.CompareTo(denominator);
        return comparison > 0 || (comparison == 0 && !quotient.IsEven) ? quotient + 1 : quotient;
    }

    /// <summary>The fixed form of a scaled integer: <paramref name="digits"/> of it after the point.</summary>
    private static string Plain(BigInteger scaled, int digits)
    {
        var text = scaled.ToString(CultureInfo.InvariantCulture);
        if (digits == 0)
        {
            return text;
        }

        if (text.Length <= digits)
        {
            text = text.PadLeft(digits + 1, '0');
        }

        return $"{text.AsSpan(0, text.Length - digits)}.{text.AsSpan(text.Length - digits)}";
    }

    /// <summary>
    /// The fixed form of a rounded significand whose first digit is at <c>10^exponent</c>: the digits
    /// are placed around the point and the fraction loses the zeros the rounding left at its end.
    /// </summary>
    private static string Significant(string digits, int exponent)
    {
        string integer;
        string fraction;
        if (exponent >= 0)
        {
            integer = digits.Length > exponent + 1 ? digits[..(exponent + 1)] : digits.PadRight(exponent + 1, '0');
            fraction = digits.Length > exponent + 1 ? digits[(exponent + 1)..] : string.Empty;
        }
        else
        {
            integer = "0";
            fraction = new string('0', -exponent - 1) + digits;
        }

        return fraction.Length == 0 ? integer : integer + "." + fraction;
    }

    /// <summary>
    /// The fixed form of Python's <c>repr</c>, which differs from <c>%g</c>'s by keeping the point of
    /// an integral value: <c>100.0</c> rather than <c>100</c>.
    /// </summary>
    private static string Repr(string digits, int decimalPoint)
    {
        if (decimalPoint <= 0)
        {
            return "0." + new string('0', -decimalPoint) + digits;
        }

        return decimalPoint >= digits.Length
            ? digits.PadRight(decimalPoint, '0') + ".0"
            : digits[..decimalPoint] + "." + digits[decimalPoint..];
    }

    /// <summary>The exponential form both <c>%g</c> and <c>repr</c> use: one leading digit, a lower-case
    /// <c>e</c>, an explicit sign and at least two exponent digits.</summary>
    private static string Exponential(string digits, int exponent)
    {
        var head = digits[..1];
        var tail = digits[1..];
        var body = tail.Length == 0 ? head : head + "." + tail;
        return body + "e" + (exponent < 0 ? "-" : "+")
            + Math.Abs(exponent).ToString("00", CultureInfo.InvariantCulture);
    }

    /// <summary>The significand as the shortest decimal string that reads back as the same double.</summary>
    private static (string Digits, int DecimalPoint) Shortest(double magnitude)
    {
        var text = magnitude.ToString("R", CultureInfo.InvariantCulture);
        var exponent = 0;
        var marker = text.IndexOf('E', StringComparison.Ordinal);
        if (marker >= 0)
        {
            exponent = int.Parse(text[(marker + 1)..], CultureInfo.InvariantCulture);
            text = text[..marker];
        }

        var point = text.IndexOf('.', StringComparison.Ordinal);
        var position = point >= 0 ? point : text.Length;
        var digits = point >= 0 ? text.Remove(point, 1) : text;
        var decimalPoint = position + exponent;
        var leading = 0;
        while (leading < digits.Length - 1 && digits[leading] == '0')
        {
            leading++;
        }

        return (digits[leading..].TrimEnd('0'), decimalPoint - leading);
    }

    /// <summary>The exponent of the leading digit: the largest <c>e</c> with <c>value &gt;= 10^e</c>.</summary>
    private static int DecimalExponent(BigInteger numerator, BigInteger denominator)
    {
        var estimate = (int)Math.Floor(BigInteger.Log10(numerator) - BigInteger.Log10(denominator));
        while (CompareWithPowerOfTen(numerator, denominator, estimate) < 0)
        {
            estimate--;
        }

        while (CompareWithPowerOfTen(numerator, denominator, estimate + 1) >= 0)
        {
            estimate++;
        }

        return estimate;
    }

    /// <summary>Whether the fraction is below, equal to or above <c>10^exponent</c>.</summary>
    private static int CompareWithPowerOfTen(BigInteger numerator, BigInteger denominator, int exponent)
    {
        var power = BigInteger.Pow(10, Math.Abs(exponent));
        return exponent >= 0
            ? numerator.CompareTo(denominator * power)
            : (numerator * power).CompareTo(denominator);
    }

    /// <summary>
    /// Whether a rendered number reads as zero. The reference answers this by parsing the digits back
    /// (`float(text.replace("-", "").replace(".", "")) == 0`); a text built only from zeros, points and
    /// signs is the same set.
    /// </summary>
    private static bool ReadsAsZero(string text) => text.AsSpan().Trim(ZeroText).IsEmpty;
}

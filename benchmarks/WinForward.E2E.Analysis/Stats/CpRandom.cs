using System.Buffers.Binary;
using System.Numerics;
using System.Security.Cryptography;
using System.Text;

namespace WinForward.E2E.Analysis.Stats;

/// <summary>
/// The reference's random number generator, reproduced: CPython's <c>random.Random(int)</c> seeded
/// through <c>init_by_array</c> with the integer's absolute value in little-endian 32-bit words,
/// MT19937's <c>genrand_uint32</c>, and <c>getrandbits(k)</c> plus <c>_randbelow(n)</c>'s rejection
/// sampling on top of it.
/// </summary>
/// <remarks>
/// <para>A general-purpose generator would be wrong here rather than merely different: the bootstrap
/// draws one number per resample and every interval in <c>verdict.json</c> is compared as text, so a
/// single differing draw in one resample changes a printed value. The port is judged against golden
/// vectors generated with CPython 3.14 and checked in
/// (<c>verification/golden/cp-random-vectors.json</c>, regenerated by
/// <c>verification/synthetic/make_cp_vectors.py</c>), which is also what makes the choice auditable
/// instead of asserted (D20.5).</para>
/// <para>Reproducing the generator is not the same as reproducing the seed derivation: a comparison's
/// seed is the run's base seed plus a hash of the metric key and the two row ids, so
/// <see cref="DeriveSeed"/> and <see cref="StableHash"/> belong to the same port.</para>
/// <para>The type is public because the test project drives it value by value, and D20.6 keeps the
/// analyzer free of an <c>InternalsVisibleTo</c>. It takes a 64-bit seed: the reference accepts an
/// integer of any size, while every seed the analysis derives is a base seed plus a value below
/// 10^6.</para>
/// </remarks>
public sealed class CpRandom
{
    private const int WordBits = 32;

    /// <summary>The state vector's length, <c>N</c> in the reference implementation.</summary>
    private const int StateSize = 624;

    /// <summary>The twist's offset, <c>M</c> in the reference implementation.</summary>
    private const int MiddleWord = 397;

    private const uint MatrixA = 0x9908b0df;
    private const uint UpperMask = 0x80000000;
    private const uint LowerMask = 0x7fffffff;

    private readonly uint[] _state = new uint[StateSize];

    /// <summary>How much of the state has been handed out; <c>N</c> means it needs twisting.</summary>
    private int _index = StateSize;

    /// <summary>Seeds a generator the way <c>random.Random(seed)</c> does.</summary>
    /// <param name="seed">The seed, used as its absolute value.</param>
    public CpRandom(long seed) => Reseed(seed);

    /// <summary>
    /// The reference's <c>stable_hash</c>: the first four bytes of the SHA-256 of the UTF-8 text, read
    /// big-endian. It is deterministic across processes, unlike a string hash, which is what lets a
    /// comparison's interval be recomputed from the command line that produced it.
    /// </summary>
    /// <param name="text">The text to hash.</param>
    /// <returns>The hash, as an unsigned 32-bit value.</returns>
    public static uint StableHash(string text)
    {
        ArgumentNullException.ThrowIfNull(text);

        Span<byte> digest = stackalloc byte[32];
        SHA256.HashData(Encoding.UTF8.GetBytes(text), digest);
        return BinaryPrimitives.ReadUInt32BigEndian(digest);
    }

    /// <summary>
    /// The seed one comparison's bootstrap draws with: the run's base seed plus the low six digits of
    /// <see cref="StableHash"/> over the text the comparison is keyed by.
    /// </summary>
    /// <param name="baseSeed">The <c>--seed</c> the analysis was called with.</param>
    /// <param name="text">The comparison's key, spelled the way the reference spells it.</param>
    /// <returns>The seed to construct a generator with.</returns>
    public static int DeriveSeed(int baseSeed, string text) => baseSeed + (int)(StableHash(text) % 1000000u);

    /// <summary>One turn of the generator, <c>genrand_uint32</c>.</summary>
    /// <returns>The next 32-bit value.</returns>
    public uint NextUInt32()
    {
        if (_index >= StateSize)
        {
            Twist();
        }

        unchecked
        {
            var value = _state[_index++];
            value ^= value >> 11;
            value ^= (value << 7) & 0x9d2c5680u;
            value ^= (value << 15) & 0xefc60000u;
            value ^= value >> 18;
            return value;
        }
    }

    /// <summary>
    /// <c>getrandbits(width)</c>: that many random bits as an unsigned value. Widths up to 32 are the
    /// top bits of one draw; a wider request fills a word array, whose last word keeps only the bits
    /// the width asks for.
    /// </summary>
    /// <param name="width">How many bits to draw, from 1 to 64.</param>
    /// <returns>A value below 2^<paramref name="width"/>.</returns>
    public ulong GetRandBits(int width)
    {
        ArgumentOutOfRangeException.ThrowIfLessThan(width, 1);
        ArgumentOutOfRangeException.ThrowIfGreaterThan(width, 64);

        if (width <= WordBits)
        {
            return NextUInt32() >> (WordBits - width);
        }

        var words = ((width - 1) / WordBits) + 1;
        var draw = 0ul;
        for (var index = 0; index < words; index++)
        {
            var word = NextUInt32();
            if (index == words - 1)
            {
                word >>= (words * WordBits) - width;
            }

            draw |= (ulong)word << (WordBits * index);
        }

        return draw;
    }

    /// <summary>
    /// <c>_randbelow(bound)</c>: a value in <c>[0, bound)</c> by rejection sampling, so the result is
    /// uniform rather than merely close to it. The draw is as wide as the bound's bit length and a
    /// draw that lands outside the range is discarded and repeated.
    /// </summary>
    /// <param name="bound">The exclusive upper bound; 1 always yields 0.</param>
    /// <returns>A value in <c>[0, bound)</c>.</returns>
    public long RandBelow(long bound)
    {
        ArgumentOutOfRangeException.ThrowIfLessThan(bound, 1);

        var width = BitOperations.Log2((ulong)bound) + 1;
        var draw = GetRandBits(width);
        while (draw >= (ulong)bound)
        {
            draw = GetRandBits(width);
        }

        return (long)draw;
    }

    /// <summary>Seeds the state from an integer's absolute value, little-endian, at least one word.</summary>
    private void Reseed(long seed)
    {
        Span<uint> key = stackalloc uint[2];
        var magnitude = Magnitude(seed);
        var length = 0;
        while (magnitude != 0)
        {
            key[length++] = (uint)magnitude;
            magnitude >>= WordBits;
        }

        InitByArray(key[..Math.Max(length, 1)]);
    }

    /// <summary>The absolute value of a signed 64-bit seed, which does not overflow on the minimum.</summary>
    private static ulong Magnitude(long seed) => seed < 0 ? (ulong)(-(seed + 1)) + 1 : (ulong)seed;

    /// <summary><c>init_genrand</c>: the state the twist starts from, before the key is folded in.</summary>
    private void InitGenRand(uint seed)
    {
        unchecked
        {
            _state[0] = seed;
            for (var index = 1; index < StateSize; index++)
            {
                _state[index] = (1812433253u * (_state[index - 1] ^ (_state[index - 1] >> 30))) + (uint)index;
            }
        }
    }

    /// <summary><c>init_by_array</c>: fold the key's words into the state, then re-mix it.</summary>
    private void InitByArray(ReadOnlySpan<uint> key)
    {
        unchecked
        {
            InitGenRand(19650218u);
            var index = 1;
            var position = 0;
            for (var remaining = Math.Max(StateSize, key.Length); remaining > 0; remaining--)
            {
                _state[index] = (_state[index] ^ ((_state[index - 1] ^ (_state[index - 1] >> 30)) * 1664525u))
                    + key[position] + (uint)position;
                index++;
                position++;
                if (index >= StateSize)
                {
                    _state[0] = _state[StateSize - 1];
                    index = 1;
                }

                if (position >= key.Length)
                {
                    position = 0;
                }
            }

            for (var remaining = StateSize - 1; remaining > 0; remaining--)
            {
                _state[index] = (_state[index] ^ ((_state[index - 1] ^ (_state[index - 1] >> 30)) * 1566083941u))
                    - (uint)index;
                index++;
                if (index >= StateSize)
                {
                    _state[0] = _state[StateSize - 1];
                    index = 1;
                }
            }

            _state[0] = 0x80000000u;
            _index = StateSize;
        }
    }

    /// <summary>The twist: regenerate all 624 words from the previous state.</summary>
    private void Twist()
    {
        unchecked
        {
            for (var index = 0; index < StateSize - MiddleWord; index++)
            {
                var joined = (_state[index] & UpperMask) | (_state[index + 1] & LowerMask);
                _state[index] = _state[index + MiddleWord] ^ (joined >> 1) ^ ((joined & 1) != 0 ? MatrixA : 0u);
            }

            for (var index = StateSize - MiddleWord; index < StateSize - 1; index++)
            {
                var joined = (_state[index] & UpperMask) | (_state[index + 1] & LowerMask);
                _state[index] = _state[index + (MiddleWord - StateSize)] ^ (joined >> 1)
                    ^ ((joined & 1) != 0 ? MatrixA : 0u);
            }

            var last = (_state[StateSize - 1] & UpperMask) | (_state[0] & LowerMask);
            _state[StateSize - 1] = _state[MiddleWord - 1] ^ (last >> 1) ^ ((last & 1) != 0 ? MatrixA : 0u);
            _index = 0;
        }
    }
}

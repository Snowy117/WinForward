using WinForward.E2E.Analysis.Findings;
using WinForward.E2E.Analysis.Model;

namespace WinForward.E2E.Analysis.Tables;

/// <summary>
/// Writes <c>tables.md</c>: one section per `## N.` heading, in the reference's own order, with the
/// batch that owns each section's body.
/// </summary>
/// <remarks>
/// <para><b>A section is a slice of the oracle.</b> The comparison between the two implementations
/// cuts <c>tables.md</c> at these headings and compares each section on its own, so the headings — not
/// just their bodies — are the batch boundaries: all sixteen exist from the first commit, their
/// bodies carry <c>&lt;!-- TODO(batch N) --&gt;</c> until the batch that owns them renders them
/// (D20.2). A missing heading would be reported as a missing slice, which is the one failure the
/// differ must never confuse with a pass.</para>
/// <para><b>The preamble is a slice too.</b> Everything before <c>## 0.</c> — the title, the
/// program-name line and the reading instructions — belongs to batch 1a, and the line that names the
/// program is neutral on purpose: it names neither implementation, so the two can be compared
/// (D6.4/D20.7).</para>
/// <para><b>The document is trimmed, then newline-terminated.</b> The reference joins its parts and
/// strips the result, so a section that ends in a blank line does not add one at the end of the file:
/// the golden ends in exactly one newline, and the compared bytes are the whole slice.</para>
/// </remarks>
internal static class TablesWriter
{
    private const string Title = "# End-to-end transparent-proxy campaign — aggregated tables";

    private const string FlatSuffix = " (flat mode: immediate subdirectories are rows of one implicit pass)";

    private const string ProgramName = "e2e-analysis v1";

    private const string AggregationPolicy =
        "**Aggregation policy.** Every aggregated number is computed over **passes**: one value per pass first, "
        + "then the median with its interquartile range `[p25–p75]` and the pass count `(n=K)` beside it. "
        + "Percentiles come from the harness's own histograms and are never recomputed. A cell that cannot be "
        + "computed is printed as `n/a (<reason>)`; a row that never ran an arm prints `not measured in this "
        + "row`; a rate the harness wrote as `null` (its denominator was zero, so nothing was sent) is printed "
        + "as an empty cell, never as a zero; and no cell averages over a pass count it does not print.";

    private const string ReadFirst =
        "**Read section 1 first.** It is generated from the single table in the source that records each row's "
        + "plan and what it does with UDP on port 53 and in general, and it explains why some rows have no "
        + "comparable UDP or DNS number at all.";

    /// <summary>
    /// Every section, in write order: the heading as the reference spells it (the differ matches
    /// <c>^## (\d+)\.</c> and compares the whole section, heading included) and the batch that
    /// renders its body.
    /// </summary>
    private static readonly (string Heading, string Batch)[] s_sections =
    [
        ("## 0. Correctness findings", "2"),
        ("## 1. What each row is and what it does with UDP", "1c"),
        ("## 2. Environment and provenance", "1c"),
        ("## 3. Gate table (one row per pass and row)", "2"),
        ("## 4. Headline matrix", "4"),
        ("## 5. Latency detail", "3"),
        ("## 6. CPU detail", "4"),
        ("## 7. Memory detail", "4"),
        ("## 8. UDP accuracy detail", "3"),
        ("## 9. DNS comparability detail", "3"),
        ("## 10. Long-lived connection detail (`PERSIST`)", "4"),
        ("## 11. TCP reliability detail", "4"),
        ("## 12. Dual-phase detail (proxied vs direct lane)", "5"),
        ("## 13. Control block comparison (`control-pre` vs `control-post`)", "5"),
        ("## 14. Target-ledger cross-check", "5"),
        ("## 15. Data availability", "1a"),
    ];

    /// <summary>Writes the document: the sections a batch has rendered, and a placeholder for the rest.</summary>
    /// <param name="writer">Where the document goes; the caller owns the encoding and the newline.</param>
    /// <param name="campaign">The tree every rendered section is read from.</param>
    /// <param name="findings">The findings §0 counts and lists, as §0.4 and the severity line both read them.</param>
    internal static void Write(TextWriter writer, CampaignModel campaign, IReadOnlyList<Finding> findings)
    {
        ArgumentNullException.ThrowIfNull(writer);
        ArgumentNullException.ThrowIfNull(campaign);
        ArgumentNullException.ThrowIfNull(findings);

        var parts = new List<string>(s_sections.Length + 8)
        {
            Title,
            string.Empty,
            $"Generated by `{ProgramName}` from `{campaign.Raw}`{(campaign.Flat ? FlatSuffix : string.Empty)}.",
            string.Empty,
            AggregationPolicy,
            string.Empty,
            ReadFirst,
            string.Empty,
        };

        foreach (var (heading, batch) in s_sections)
        {
            parts.Add(Section(heading, campaign, findings, batch));
        }

        writer.Write(string.Join('\n', parts).TrimEnd() + "\n");
    }

    /// <summary>One section: its heading, a blank line, and a body that ends in a newline.</summary>
    private static string Section(
        string heading,
        CampaignModel campaign,
        IReadOnlyList<Finding> findings,
        string batch)
    {
        var number = heading[3..heading.IndexOf('.', StringComparison.Ordinal)];
        var body = number switch
        {
            "0" => TableFindings.RenderBody(campaign, findings),
            "1" => TableRowProfiles.RenderBody(campaign),
            "2" => TableEnvironment.RenderBody(campaign),
            "3" => TableGates.RenderBody(campaign),
            "4" => TableHeadline.RenderBody(campaign),
            "5" => TableLatency.RenderBody(campaign),
            "6" => TableCpu.RenderBody(campaign),
            "7" => TableMemory.RenderBody(campaign),
            "8" => TableUdp.RenderBody(campaign),
            "9" => TableDns.RenderBody(campaign),
            "10" => TablePersist.RenderBody(campaign),
            "11" => TableTcp.RenderBody(campaign),
            "15" => TableAvailability.RenderBody(campaign),
            _ => $"<!-- TODO(batch {batch}) -->\n",
        };

        return heading + "\n\n" + body;
    }
}
